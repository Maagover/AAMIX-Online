"""Build reviewed additive SQL from the shipped catalogue and exact legacy deck.

This prepares files only. It never connects to Supabase or applies SQL.

Historical 0.10.0 generator: its original draw includes promotional normals.
For the current pack rules, apply the additive aamix_no_promo_packs.sql correction
AFTER the original 0.10.0 migration. Do not replay the original migration against
an existing installation. This generator does not produce or deploy that correction.
"""
from pathlib import Path
import json

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
catalogue = json.loads((ROOT / 'data/catalogo_edicion_1.json').read_text(encoding='utf-8'))['cartas']
legacy = json.loads((ROOT / 'tests/fixtures/mazos_legacy.json').read_text(encoding='utf-8'))['mazos']
maago = next(d for d in legacy if d['id'] == 'usuario_maagover')
special_weights = {'0105': 5, '0103': 5, '0115': 5, '0119': 5,
                   '0134': 16, '0128': 16, '0125': 16, '0131': 16, '0130': 16}
assert sum(special_weights.values()) == 100
assert len(catalogue) == 41
assert sum(c['cantidad'] for c in maago['cartas']) == 40
assert next(c['cantidad'] for c in maago['cartas'] if c['codigo'] == '0100') == 15
assert len([c for c in catalogue if c['clase'] != 'Recurso' and c['codigo'] not in special_weights]) == 31

def literal(value):
    return "'" + str(value).replace("'", "''") + "'"

seed = '-- Generated by backend/build_rewards.py; all 41 catalogue cards are collectible.\n'
seed += 'insert into aamix_private.reward_catalog(code,name,card_class,special_weight) values\n'
seed += ',\n'.join('(' + ','.join((literal(c['codigo']), literal(c['nombre']), literal(c['clase']), str(special_weights.get(c['codigo'], 0)))) + ')' for c in catalogue) + ';\n'
seed += 'insert into aamix_private.base_decks(id,name,cover,cards) values (' + ','.join((literal('maago'), literal('Mazo Maagover'), literal('0108'), literal(json.dumps(maago['cartas'], ensure_ascii=False)) + '::jsonb')) + ');\n'
template = (HERE / 'rewards_template.sql').read_text(encoding='utf-8')
assert template.count('-- CATALOGUE_AND_MAAGO_SEED') == 1
(HERE / 'aamix_rewards.sql').write_text(template.replace('-- CATALOGUE_AND_MAAGO_SEED', seed), encoding='utf-8')
print('Prepared rewards SQL: 41 cards, 31 normal, 9 special, 1 resource; exact Maago 40/15.')
